# Lexicon.ps1 - regenerate Client/Utilities/Lexicon.hpp from Shared/Protocol.h.
# Lives in Build/Scripts/.
#
# The client must not ship plaintext diagnostic labels (INJECT, UNLOAD_OWNER,
# STATUS_NOT_IMPLEMENTED, ...) because they advertise the driver command surface.
# This script reads the X-macro tables in Protocol.h, XOR-encodes each label at
# build time, and writes a header of numeric arrays that decode at runtime. No
# readable label string ever exists in the compiled binary or in source.
#
# Run automatically by Create.bat before compiling the client. Safe to run by
# hand: the output is deterministic, so regeneration is a no-op when Protocol.h
# has not changed.

param(
    [string]$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
)

$ErrorActionPreference = 'Stop'
$protocol = Join-Path $Root 'Shared\Protocol.h'
$output = Join-Path $Root 'Client\Utilities\Lexicon.hpp'

if (-not (Test-Path $protocol)) { throw "Protocol.h not found: $protocol" }
$src = Get-Content -LiteralPath $protocol -Raw

# Status table: X(0x........u, STATUS_NAME)
$statusPairs = @()
foreach ($m in [regex]::Matches($src, 'X\((0x[0-9A-Fa-f]+u),\s*([A-Z][A-Z0-9_]*)\)')) {
    $statusPairs += [pscustomobject]@{ Code = $m.Groups[1].Value; Name = $m.Groups[2].Value }
}
# Log table: X(AMGER_LOG_ID_..., NAME)
$logPairs = @()
foreach ($m in [regex]::Matches($src, 'X\((AMGER_LOG_ID_[A-Z_]+),\s*([A-Z][A-Z0-9_]*)\)')) {
    $logPairs += [pscustomobject]@{ Code = $m.Groups[1].Value; Name = $m.Groups[2].Value }
}
if ($statusPairs.Count -eq 0 -or $logPairs.Count -eq 0) {
    throw "Could not extract label tables from $protocol"
}

$key = 0x5A3C
$out = [System.Collections.Generic.List[string]]::new()
$out.Add('// GENERATED by Build/Scripts/Lexicon.ps1. Do not edit by hand.')
$out.Add('// Status/log labels are XOR-encoded numeric arrays to avoid plaintext')
$out.Add('// diagnostic labels in the Client.exe image; Main.cpp deliberately renders')
$out.Add('// other plaintext UI strings. Each label decodes into its own static buffer')
$out.Add('// so equal-length labels never alias mid-expression.')
$out.Add('#pragma once')
$out.Add('#include <array>')
$out.Add('#include <cstddef>')
$out.Add('')
$out.Add('#include "../../Shared/Protocol.h"')
$out.Add('')
$out.Add('namespace Labels {')
$out.Add(('constexpr wchar_t kLabelKey = 0x{0:X4}u;' -f $key))

$idx = 0
foreach ($pair in (@($statusPairs) + @($logPairs))) {
    $chars = $pair.Name.ToCharArray()
    $vals = @()
    for ($i = 0; $i -lt $chars.Length; $i++) {
        $vals += ('0x{0:X4}' -f ([int][char]$chars[$i] -bxor ($key + $i)))
    }
    # trailing NUL, encoded
    $vals += ('0x{0:X4}' -f (0 -bxor ($key + $chars.Length)))
    $sym = 'kL' + $idx
    $out.Add("static constexpr std::array<wchar_t, $($vals.Count)> $sym = { $($vals -join ', ') };")
    $idx++
}

$out.Add('')
$out.Add('template <std::size_t N>')
$out.Add('inline void Decode(const std::array<wchar_t, N>& a, wchar_t* destination) {')
$out.Add('  for (std::size_t i = 0; i < N; ++i)')
$out.Add('    destination[i] = static_cast<wchar_t>(static_cast<unsigned>(a[i]) ^ (kLabelKey + i));')
$out.Add('}')
$out.Add('}  // namespace Labels')
$out.Add('')
# Each label decodes into its OWN function-local static buffer. A single buffer
# keyed by length N aliases labels of equal length (e.g. STATUS_SUCCESS and a
# 15-char log name), so two labels decoded in one expression corrupt each other.
$out.Add('inline const wchar_t* LabelStatus(uint32_t code) {')
$out.Add('  switch (code) {')
for ($i = 0; $i -lt $statusPairs.Count; $i++) {
    $n = $statusPairs[$i].Name.Length + 1
    $out.Add("    case $($statusPairs[$i].Code): { static wchar_t b[$n]; Labels::Decode(Labels::kL$i, b); return b; }")
}
$out.Add('    default: break;')
$out.Add('  }')
$out.Add('  return nullptr;')
$out.Add('}')
$out.Add('')
$out.Add('inline const wchar_t* LabelLog(uint16_t id) {')
$out.Add('  switch (id) {')
for ($i = 0; $i -lt $logPairs.Count; $i++) {
    $so = $statusPairs.Count + $i
    $n = $logPairs[$i].Name.Length + 1
    $out.Add("    case $($logPairs[$i].Code): { static wchar_t b[$n]; Labels::Decode(Labels::kL$so, b); return b; }")
}
$out.Add('    default: break;')
$out.Add('  }')
$out.Add('  return nullptr;')
$out.Add('}')

[IO.File]::WriteAllLines($output, $out)
Write-Host "[Lexicon] Wrote $idx labels to $output"
